import { describe, expect, it } from "vitest";
import {
  changePassphrase,
  createVault,
  decodeMemo,
  decodeVault,
  decryptMemo,
  encodeRecord,
  encryptMemo,
  recoverVault,
  unlockVault,
} from "../src/lib/e2ee/crypto";
import vector from "./fixtures/e2ee-v1.json";

describe("E2EE protocol", () => {
  it("opens from a second device and recovers after changing the separate passphrase", async () => {
    const created = await createVault("a long independent encryption passphrase");
    const remote = decodeVault(encodeRecord(created.record));
    const secondKey = await unlockVault(remote, "a long independent encryption passphrase");
    const encrypted = await encryptMemo(secondKey, remote.id, "# private canary text");
    expect(JSON.stringify(encrypted)).not.toContain("private canary text");
    expect(await decryptMemo(created.key, encrypted)).toBe("# private canary text");
    await expect(unlockVault(remote, "wrong secret")).rejects.toThrow();
    const recovered = await recoverVault(remote, created.recoverySecret);
    const changed = await changePassphrase(remote, recovered, "another independent encryption passphrase");
    expect(changed.id).toBe(remote.id);
    expect(changed.revision).not.toBe(remote.revision);
    const changedKey = await unlockVault(changed, "another independent encryption passphrase");
    expect(await decryptMemo(changedKey, encrypted)).toBe("# private canary text");
    await expect(unlockVault(changed, "a long independent encryption passphrase")).rejects.toThrow();
    expect(await decryptMemo(await recoverVault(changed, created.recoverySecret), encrypted)).toBe("# private canary text");
  });
  it("rejects tampered ciphertext and context substitution; revisions use fresh keys", async () => {
    const { key, record } = await createVault("a long independent encryption passphrase");
    const a = await encryptMemo(key, record.id, "secret");
    const b = await encryptMemo(key, record.id, "secret", a.objectId);
    expect(a.revisionId).not.toBe(b.revisionId);
    expect(a.body.ciphertext).not.toBe(b.body.ciphertext);
    expect(a.dataKey.ciphertext).not.toBe(b.dataKey.ciphertext);
    for (const field of ["vaultId", "objectId", "revisionId"] as const) {
      await expect(decryptMemo(key, { ...a, [field]: crypto.randomUUID() })).rejects.toThrow();
    }
    await expect(decryptMemo(key, { ...a, dataKey: b.dataKey })).rejects.toThrow();
    await expect(decryptMemo(key, { ...a, body: { ...a.body, ciphertext: `${a.body.ciphertext.slice(0, -4)}AAAA` } })).rejects.toThrow();
    await expect(decryptMemo(key, { ...a, version: 2 } as never)).rejects.toThrow();
  });
  it("rejects unsupported and oversized key records before deriving keys", () => {
    expect(() => decodeVault(new Uint8Array(20000))).toThrow();
    expect(() => decodeVault(encodeRecord({ version: 2 }))).toThrow();
  });
});

it("decrypts the fixed protocol vector generated by independent OpenSSL code", async () => {
  const raw = Uint8Array.from(vector.vaultKey.match(/../g) ?? [], (pair) => Number.parseInt(pair, 16));
  const key = await crypto.subtle.importKey("raw", raw, "AES-GCM", false, ["decrypt"]);
  expect(await decryptMemo(key, decodeMemo(encodeRecord(vector.envelope)))).toBe(vector.plaintext);
});

it("round-trips the maximum UTF-8 body and rejects one byte over the limit", async () => {
  const key = await crypto.subtle.generateKey({ name: "AES-GCM", length: 256 }, false, ["encrypt", "decrypt"]);
  const text = "x".repeat(1024 * 1024);
  const encrypted = await encryptMemo(key, crypto.randomUUID(), text);
  expect(await decryptMemo(key, encrypted)).toBe(text);
  await expect(encryptMemo(key, crypto.randomUUID(), `${text}x`)).rejects.toThrow("too large");
});
